-- 김찬영(1)의 거래내역을 매수 두 건으로 통째로 다시 세운다.
--
-- **요청.** 최초 가상현금 10,000,000원으로 LG전자 30주(주당 182,000원)와 농심 10주(주당
-- 386,000원)만 사고 현금 680,000원이 남은 계좌로 만든다.
--
--   30 × 182,000 = 5,460,000
--   10 × 386,000 = 3,860,000
--   10,000,000 − 9,320,000 = 680,000   ← 요청한 현금과 원 단위까지 맞는다
--
-- **그래서 "두 건 추가"가 아니라 "전량 교체"다.** 잔액은 `10,000,000 − 매수 + 매도` 로만
-- 정해지므로(`rebuild_holdings`), 기존 체결이 한 건이라도 남으면 680,000이 나오지 않는다.
-- 적용 시점 라이브에는 김찬영 거래가 43건(체결 24 · 예약 4 · 취소 15) 있었고 보유는
-- 크래프톤 24.043주 · 하이브 25주 · 삼성전자 0.181주, 잔액 954,400.0007원이었다.
--
-- **날짜를 요청과 다르게 잡았다.** 요청은 8/12(LG전자)·8/14(농심)였지만 보관된 일봉과
-- 어긋난다. 차트 마커는 체결가를 y 로 쓰므로 캔들 밖 가격은 허공에 뜬 핀이 된다.
--
--   LG전자 8/12 은 202,500~211,500 이라 182,000 이 한참 아래다 → 8/10(181,700~187,700)
--   농심 8/14 은 아예 휴장이다. `stock_candles` 가 8/13 다음 8/17 로 건너뛴다 → 8/11
--
-- 농심 386,000 은 8/11 저가 386,500 보다 500원(0.13%) 아래다. 정확히 들어맞는 날은
-- 7/30(고가 386,000)뿐인데 그러면 LG전자(8/10)보다 앞서서 매수 순서가 뒤집힌다. 가격을
-- 바꾸면 현금 680,000이 깨지므로 날짜만 옮기고 500원 차이는 남긴다 — 핀은 캔들에 붙는다.
--
-- 시각은 `01:00+00` = KST 10:00 이다. 화면이 체결일을 `Asia/Seoul` 로 읽으므로
-- (`web/features/f0-home/lib/chart-trade-legend.ts`) 이래야 의도한 날짜에 떨어진다.
--
-- **함께 사라지는 것.** 김찬영 거래에 달린 부모 댓글 3개·좋아요 5개, 8/3~8/18 행동 기록,
-- 미체결 예약 4건(하이브 매도 12.5주, 오리온 매수 2건, 삼성전자 매수 1건, 잠긴 현금
-- 30,000원)이 전부 없어진다. 아카이브 성향 카드는 매수 2건만으로 다시 계산된다. 사용자가
-- 이 결과를 알고 선택했다. 예약은 지우면 그만이라 `cancel_order` 를 따로 부르지 않는다 —
-- 잠긴 자원은 아래 `rebuild_holdings` 가 남은 거래에서 다시 낸다.
--
-- **두 번 돌려도 같은 상태다.** 새로 넣는 두 건은 id 를 고정해 삭제에서 빼고
-- `on conflict do nothing` 으로 넣는다. 빈 DB 에서는 지울 것이 없고 두 건만 생긴다.

begin;

-- ── 1. 김찬영의 기존 거래와 그에 달린 반응 ──────────────────────────────────
-- 반응을 먼저 지운다. 거래를 먼저 지우면 cascade 가 처리하지만, 지우는 대상을 눈에
-- 보이게 적어 두는 편이 나중에 이 파일을 읽을 때 무엇이 사라졌는지 알기 쉽다.
delete from public.trade_likes
  where transaction_id in (select id from public.transactions where user_id = 1);
delete from public.trade_comments
  where transaction_id in (select id from public.transactions where user_id = 1);

delete from public.transactions
  where user_id = 1
    and id not in ('e9a10000-0000-4000-8000-000000000001',
                   'e9a10000-0000-4000-8000-000000000002');

delete from public.holdings where user_id = 1;

-- ── 2. 매수 두 건 ───────────────────────────────────────────────────────────
-- `trade_reason` 은 not null 이다. 둘 다 아는 회사를 고른 것으로 두어 근거 코드
-- (`EVIDENCE_REASON_CODES`)에 드는 값을 쓴다.
insert into public.transactions
  (id, user_id, stock_id, side, trade_price, trade_quantity, trade_reason,
   order_status, order_type, created_at, filled_at)
values
  ('e9a10000-0000-4000-8000-000000000001', 1, 14, 'buy', 182000, 30, 'buy_familiar',
   'filled', 'market', '2026-08-10 01:00:00+00', '2026-08-10 01:00:00+00'),
  ('e9a10000-0000-4000-8000-000000000002', 1, 13, 'buy', 386000, 10, 'buy_familiar',
   'filled', 'market', '2026-08-11 01:00:00+00', '2026-08-11 01:00:00+00')
on conflict (id) do nothing;

-- ── 3. 보유·잔액 재계산 ─────────────────────────────────────────────────────
-- `transactions` 와 `holdings` 를 잇는 트리거가 없어 거래만 고치면 차트만 바뀌고 홈은 옛
-- 값 그대로다(README "거래내역을 직접 고쳤다면"). 여기서 직접 부른다.
--   → holdings 2행 (LG전자 30 @182,000 · 농심 10 @386,000, 예약 잠금 0)
--   → account   balance 680,000 · reserved_balance 0
select public.rebuild_holdings(1);

commit;
