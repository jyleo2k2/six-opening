-- 무게를 실었으며(저격수), 이번 주에는 그 반도체를 도로 다 팔아 원래 좋아하던
-- 크래프톤·하이브에 몰아 담았다(승부사 — 찾아보지 않았지만 돈은 두 종목에 몰려 있다).
